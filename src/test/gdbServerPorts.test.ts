/** A launch.json as CMSIS Solution writes it: a launch and an attach configuration, with a comment. */
function launchJson(port: number | string, host?: string): string {
    return `{
    // generated by CMSIS Solution
    "version": "0.2.0",
    "configurations": [
        { "name": "STLink@pyOCD (launch)", "type": "gdbtarget", "request": "launch", "target": { "server": "pyocd", "port": "3333" } },
        { "name": "STLink@pyOCD (attach)", "type": "gdbtarget", "request": "attach", "target": { ${host ? `"host": "${host}", ` : ''}"port": ${JSON.stringify(port)} } },
        { "name": "Python", "type": "debugpy", "request": "attach", "connect": { "port": 5678 } },
    ]
}`;
}

